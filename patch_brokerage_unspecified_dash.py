new='''仲介手数料はユーザーが明示指定した場合だけ金額を入れてください。『なし』『無料』『0円』は0円、『5万円』などの円指定はその金額、『0.5ヶ月』『1ヶ月』などの月数指定はその指定に従って計算してください。ユーザーから今回の見積もりについて仲介手数料の指定がない場合は、図面記載・一般的な相場・保存済み会社ルール・過去の見積もりに金額があっても必ず「－」としてください。仲介手数料を自動で家賃1ヶ月＋税等にしないでください。'''
